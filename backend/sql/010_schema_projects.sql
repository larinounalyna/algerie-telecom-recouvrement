-- Projets, avenants, pièces remises et documents numériques.
-- Idempotent additive migration; existing tables and records are untouched.

CREATE TABLE IF NOT EXISTS project_ar_project (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(255) NOT NULL,
    contract_number VARCHAR(100) NOT NULL,
    amendment_numbers JSON NOT NULL DEFAULT '[]',
    launch_date DATE NOT NULL,
    pieces_remises JSON NOT NULL DEFAULT '[]',
    end_date DATE,
    estimated_amount NUMERIC(14, 2) CHECK (estimated_amount >= 0),
    final_invoice_amount NUMERIC(14, 2) CHECK (final_invoice_amount >= 0),
    payment_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_project_ar_project_name ON project_ar_project (project_name);
CREATE INDEX IF NOT EXISTS idx_project_ar_contract_number ON project_ar_project (contract_number);

CREATE TABLE IF NOT EXISTS project_ar_file (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id INTEGER NOT NULL REFERENCES project_ar_project(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size INTEGER NOT NULL,
    data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_project_ar_file_project ON project_ar_file (project_id);

CREATE OR REPLACE FUNCTION update_project_ar_project_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_project_ar_project_updated_at ON project_ar_project;

CREATE TRIGGER trg_project_ar_project_updated_at
BEFORE UPDATE ON project_ar_project
FOR EACH ROW
EXECUTE FUNCTION update_project_ar_project_timestamp();
